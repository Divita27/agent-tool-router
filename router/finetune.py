"""Fine-tune the e5-small embedding model on generated caller queries (contrastive learning).

Run from the project folder:  python -m router.finetune

Training pairs: (caller query, tool document). Each batch holds different tools, and the loss
pulls every query toward its own tool and away from the other tools in the batch
(in-batch negatives, as in MultipleNegativesRankingLoss).

Training data = queries generated by sarvam-105b from tool definitions only, plus the
distractor tools' examples. The dev set (Claude) and the LLM test set (from scenario cards)
are NEVER used for training, so evaluation stays independent.
"""
import json
import random
import time
from pathlib import Path

import torch
import torch.nn.functional as F
from sentence_transformers import SentenceTransformer

from router.index import MODELS, distractor_entries, document, real_entries

OUT = Path(MODELS["e5-ft"][0])
BASE = MODELS["e5-small"][0]
EPOCHS, BATCH, LR, SCALE = 2, 32, 2e-5, 20.0


def pairs():
    out = []
    for e in real_entries() + distractor_entries(400):
        doc = "passage: " + document(e, with_examples=True)
        texts = e.synthetic if e.real else e.examples
        out += [("query: " + q, doc, e.name) for q in texts]
    return out


def batches(data, rng):
    """Shuffle, then fill batches so no tool appears twice in one batch (it would be its own negative)."""
    data = data[:]
    rng.shuffle(data)
    pending = data
    while pending:
        batch, used, rest = [], set(), []
        for p in pending:
            if len(batch) < BATCH and p[2] not in used:
                batch.append(p)
                used.add(p[2])
            else:
                rest.append(p)
        yield batch
        pending = rest


def main():
    import os
    device = os.environ.get("DEVICE") or ("mps" if torch.backends.mps.is_available() else "cpu")
    rng = random.Random(0)
    data = pairs()
    print(f"{len(data)} training pairs on {device}")
    model = SentenceTransformer(BASE, device=device)
    model.max_seq_length = 128
    model.train()
    opt = torch.optim.AdamW(model.parameters(), lr=LR)

    def encode(texts):
        feats = model.tokenize(texts)
        feats = {k: v.to(device) if torch.is_tensor(v) else v for k, v in feats.items()}
        return F.normalize(model(feats)["sentence_embedding"], dim=-1)

    start = time.time()
    for epoch in range(EPOCHS):
        losses = []
        for batch in batches(data, rng):
            if len(batch) < 4:
                continue
            q = encode([b[0] for b in batch])
            d = encode([b[1] for b in batch])
            loss = F.cross_entropy(SCALE * q @ d.T, torch.arange(len(batch), device=device))
            opt.zero_grad()
            loss.backward()
            opt.step()
            losses.append(loss.item())
            if len(losses) % 5 == 0:
                print(f"  step {len(losses)}: loss {loss.item():.3f} ({time.time() - start:.0f}s)", flush=True)
        print(f"epoch {epoch + 1}: loss {sum(losses) / len(losses):.3f}  ({time.time() - start:.0f}s)")

    model.eval()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    model.save(str(OUT))
    (OUT / "training.json").write_text(json.dumps({"base": BASE, "pairs": len(data), "epochs": EPOCHS,
                                                    "batch": BATCH, "lr": LR, "scale": SCALE}, indent=1))
    print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
