"""The 111 tools the agent can use, one entry per backend handler.

What the model sees:   name, description, parameters  (see tools/__init__.py: schema())
What only we see:      area, risk, examples           (used by the router and the safety layer)

Risk levels (the safety layer in Step 10 decides what each one requires):
    read          looks something up, changes nothing
    write         changes something, can be undone or is only a request
    payment       moves money
    pii           reads or changes sensitive personal data
    irreversible  can't be undone (closing a loan, blocking a card, ...)

Examples are short phrases a caller might say, in Hinglish, Hindi and English.
The router may learn from them, so they must NEVER be reused as test data.
"""
from dataclasses import dataclass, field


@dataclass
class Param:
    type: str                       # string | number | integer
    description: str
    enum: list = None
    required: bool = True


@dataclass
class Tool:
    name: str
    area: str
    risk: str
    description: str
    params: dict = field(default_factory=dict)
    examples: list = field(default_factory=list)


